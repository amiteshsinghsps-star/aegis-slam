"""Synthetic sequence generator for AEGIS-SLAM.

A real SLAM dataset (TUM/KITTI) is tens of GB and cannot be bundled in a
competition repo, and the environment may have no network access. AEGIS-SLAM
therefore ships a deterministic renderer that projects a fixed 3-D point cloud
through a moving pinhole camera, producing:

  * an image sequence (PNG frames),
  * a TUM-style ``rgb.txt`` list and ``groundtruth.txt`` (camera→world poses),
  * an ``intrinsics.json`` with K,
  * an optional MP4 (for the custom-video upload path),

The frames are generated by genuine projective geometry, so the reused
OpenCV-5 SLAM core can bootstrap, track and triangulate against them, and the
ground truth lets the evaluation harness compute ATE. This makes the whole
fault-injection benchmark reproducible offline.
"""
from __future__ import annotations

import argparse
import json
import os
from typing import List, Tuple

import cv2
import numpy as np

from aegis.geom import rotation_about_axis


def _look_at_R_cw(yaw: float, pitch: float, roll: float) -> np.ndarray:
    """Camera-from-world rotation for a camera looking down +Z with wobble.

    OpenCV camera axes: x right, y down, z forward. World is defined as the
    camera frame at t=0 (identity pose), so the base R_cw is the identity and
    we apply small yaw/pitch/roll perturbations about the camera axes.
    """
    Ry = rotation_about_axis([0, 1, 0], yaw)      # yaw about vertical
    Rx = rotation_about_axis([1, 0, 0], pitch)    # pitch about horizontal
    Rz = rotation_about_axis([0, 0, 1], roll)     # in-plane roll
    return Ry @ Rx @ Rz


def build_trajectory(n_frames: int, seed: int = 0):
    """Smooth forward motion with gentle wobble. Returns list of (C_w, R_cw)."""
    rng = np.random.default_rng(seed)
    phase = rng.uniform(0, 2 * np.pi, size=4)
    traj: List[Tuple[np.ndarray, np.ndarray]] = []
    for i in range(n_frames):
        t = i / float(max(n_frames - 1, 1))
        # forward drift plus a lissajous lateral/vertical sway (a baseline for parallax)
        C = np.array([
            0.35 * np.sin(2.0 * np.pi * t + phase[0]),
            0.20 * np.sin(2.0 * np.pi * t * 1.5 + phase[1]),
            0.5 + 3.2 * t,          # move forward in +Z
        ])
        yaw = 0.10 * np.sin(2.0 * np.pi * t * 0.8 + phase[2])
        pitch = 0.05 * np.sin(2.0 * np.pi * t * 1.1 + phase[3])
        roll = 0.02 * np.sin(2.0 * np.pi * t * 2.0)
        R_cw = _look_at_R_cw(yaw, pitch, roll)
        traj.append((C, R_cw))
    return traj


def _rotation_matrix_to_quat_xyzw(R: np.ndarray) -> np.ndarray:
    from scipy.spatial.transform import Rotation
    return Rotation.from_matrix(R).as_quat()  # (x, y, z, w)


def generate_scene(n_points: int = 1400, seed: int = 0) -> np.ndarray:
    """Random point cloud in front of the camera corridor, world coords (N,3)."""
    rng = np.random.default_rng(seed + 991)
    X = np.empty((n_points, 3), dtype=np.float64)
    X[:, 0] = rng.uniform(-2.5, 2.5, n_points)     # x (lateral)
    X[:, 1] = rng.uniform(-1.8, 1.8, n_points)     # y (vertical)
    X[:, 2] = rng.uniform(0.8, 9.0, n_points)      # z (depth, always ahead)
    return X


def render_frame(X: np.ndarray, C: np.ndarray, R_cw: np.ndarray,
                 K: np.ndarray, width: int, height: int,
                 gray: np.ndarray, blur_px: float = 0.0) -> np.ndarray:
    """Project the point cloud to a BGR frame through the pinhole camera."""
    t_cw = -R_cw @ C
    Xc = (R_cw @ X.T).T + t_cw                      # camera coords
    z = Xc[:, 2]
    front = z > 1e-6
    Xc, depth = Xc[front], z[front]
    g = gray[front]

    uv = (K @ (Xc / depth[:, None]).T).T[:, :2]
    u = np.round(uv[:, 0]).astype(np.int32)
    v = np.round(uv[:, 1]).astype(np.int32)
    inside = (u >= 0) & (u < width) & (v >= 0) & (v < height)
    u, v, depth = u[inside], v[inside], depth[inside]
    g = g[inside]

    # near-white background so points read as dark texture
    img = np.full((height, width, 3), 232, dtype=np.uint8)
    # dot radius shrinks with depth (perspective), 1..4 px
    r = np.clip(np.round(260.0 / depth), 1, 4).astype(np.int32)
    val = np.clip(g * 255, 20, 200).astype(np.uint8)
    for uu, vv, rr, gg in zip(u, v, r, val):
        cv2.circle(img, (int(uu), int(vv)), int(rr), (int(gg), int(gg), int(gg)), -1, cv2.LINE_AA)

    if blur_px and blur_px > 0.6:
        k = int(blur_px) * 2 + 1
        img = cv2.GaussianBlur(img, (k, k), 0)
    return img


def make_dataset(out_dir: str, n_frames: int = 240, seed: int = 0,
                 width: int = 640, height: int = 480,
                 write_mp4: bool = True) -> dict:
    """Render a clean sequence and persist TUM-style layout + intrinsics."""
    os.makedirs(out_dir, exist_ok=True)
    rgb_dir = os.path.join(out_dir, "rgb")
    os.makedirs(rgb_dir, exist_ok=True)

    K = np.array([[500.0, 0.0, width / 2.0],
                  [0.0, 500.0, height / 2.0],
                  [0.0, 0.0, 1.0]], dtype=np.float64)

    rng = np.random.default_rng(seed + 7)
    X = generate_scene(seed=seed)
    gray = rng.uniform(0.1, 0.9, size=len(X))
    traj = build_trajectory(n_frames, seed=seed)

    fps = 30.0
    t0 = 1_600_000_000.0
    rgb_lines, gt_lines = [], []
    writer = None
    if write_mp4:
        mp4_path = os.path.join(out_dir, "sequence.mp4")
        writer = cv2.VideoWriter(mp4_path, cv2.VideoWriter_fourcc(*"mp4v"),
                                 fps, (width, height))

    for i, (C, R_cw) in enumerate(traj):
        img = render_frame(X, C, R_cw, K, width, height, gray)
        name = f"image_{i:05d}.png"
        cv2.imwrite(os.path.join(rgb_dir, name), img)
        ts = t0 + i / fps
        rgb_lines.append(f"{ts:.6f} rgb/{name}")

        R_wc = R_cw.T
        q = _rotation_matrix_to_quat_xyzw(R_wc)  # xyzw
        gt_lines.append(f"{ts:.6f} {C[0]:.6f} {C[1]:.6f} {C[2]:.6f} "
                        f"{q[0]:.6f} {q[1]:.6f} {q[2]:.6f} {q[3]:.6f}")
        if writer is not None:
            writer.write(img)

    if writer is not None:
        writer.release()

    with open(os.path.join(out_dir, "rgb.txt"), "w") as f:
        f.write("# timestamp relative_path\n")
        f.write("\n".join(rgb_lines) + "\n")
    with open(os.path.join(out_dir, "groundtruth.txt"), "w") as f:
        f.write("# timestamp tx ty tz qx qy qz qw (camera->world)\n")
        f.write("\n".join(gt_lines) + "\n")
    intr = {
        "width": width, "height": height, "fps": fps,
        "K": K.tolist(),
        "model": "pinhole",
        "n_frames": n_frames,
        "seed": seed,
    }
    with open(os.path.join(out_dir, "intrinsics.json"), "w") as f:
        json.dump(intr, f, indent=2)

    manifest = {
        "dir": out_dir, "rgb_txt": os.path.join(out_dir, "rgb.txt"),
        "gt_txt": os.path.join(out_dir, "groundtruth.txt"),
        "intrinsics": os.path.join(out_dir, "intrinsics.json"),
        "mp4": os.path.join(out_dir, "sequence.mp4") if write_mp4 else None,
        "n_frames": n_frames,
    }
    with open(os.path.join(out_dir, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    return manifest


def load_intrinsics(out_dir: str) -> dict:
    with open(os.path.join(out_dir, "intrinsics.json")) as f:
        return json.load(f)


def _main():
    ap = argparse.ArgumentParser("AEGIS-SLAM synthetic dataset generator")
    ap.add_argument("--out", default="Dataset/synthetic")
    ap.add_argument("--frames", type=int, default=240)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--width", type=int, default=640)
    ap.add_argument("--height", type=int, default=480)
    ap.add_argument("--no_mp4", action="store_true")
    args = ap.parse_args()
    m = make_dataset(args.out, n_frames=args.frames, seed=args.seed,
                     width=args.width, height=args.height, write_mp4=not args.no_mp4)
    print("Wrote synthetic dataset:", json.dumps(m, indent=2))


if __name__ == "__main__":
    _main()
